class GeoBenchSegDataset(Dataset):
    def __init__(self, task, split: str, augment: bool = False):
        super().__init__()
        self.dataset   = task.get_dataset(split=split)
        self.augment   = augment
        self.band_names = self.dataset[0].band_names
        self.band_indices = BAND_INDICES

        self.mean = torch.tensor(prithvi_vit.PRITHVI_V2_MEAN, dtype=torch.float32)[:, None, None]
        self.std  = torch.tensor(prithvi_vit.PRITHVI_V2_STD,  dtype=torch.float32)[:, None, None]

        self._spatial_aug = albumentations.Compose([
            albumentations.HorizontalFlip(p=0.5),
            albumentations.VerticalFlip(p=0.5),
            albumentations.Resize(224, 224),
        ])
        self._spatial_val = albumentations.Compose([
            albumentations.Resize(224, 224),
        ])

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):
        sample = self.dataset[idx]
        image = sample.pack_to_3d(band_names=self.band_names)[0].astype(np.float32)
        image = image[:, :, self.band_indices]
        mask  = sample.label.data.astype(np.int64)

        tfm = self._spatial_aug if self.augment else self._spatial_val
        out = tfm(image=image, mask=mask)
        image = out["image"]
        mask  = out["mask"]

        x = torch.tensor(image).permute(2, 0, 1).float()
        x = (x - self.mean) / self.std
        y = torch.tensor(mask).long()

        sid = str(sample.sample_name)
        return x, y, sid


